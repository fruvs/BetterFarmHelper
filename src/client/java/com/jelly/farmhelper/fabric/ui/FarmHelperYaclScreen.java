    public static Screen create(Screen parent) {
        FarmHelperConfig config = FarmHelperFabric.getConfigManager().getConfig();
        return YetAnotherConfigLib.createBuilder()
                .title(Text.literal("FarmHelper Settings"))
                .category(buildMacroCategory(config))
                .category(buildFailsafesCategory(config))
                .category(buildAutomationCategory(config))
                .category(buildPestsCategory(config))
                .category(buildDisplayCategory(config, parent))
                .category(buildConnectionsCategory(config))
                .category(buildKeybindsCategory(config))
                .category(buildFeatureTogglesCategory(config))
                .save(() -> FarmHelperFabric.getConfigManager().save())
                .build()
                .generateScreen(parent);
    }


