    private static ConfigCategory buildFeatureTogglesCategory(FarmHelperConfig config) {
        ConfigCategory.Builder builder = ConfigCategory.createBuilder()
                .name(Text.literal("Feature Toggles"))
                .tooltip(Text.literal("Enable or disable individual feature modules"));

        for (FeatureCatalog.FeatureDefinition def : FeatureCatalog.DEFINITIONS) {
            boolean defaultValue = DEFAULT_TRUE_FEATURES.contains(def.id());
            builder.option(Option.<Boolean>createBuilder()
                    .name(Text.literal(def.displayName()))
                    .description(desc("Enable or disable the " + def.displayName() + " module. Toggle off to save resources if you don't use this feature."))
                    .binding(
                            defaultValue,
                            () -> config.featureToggles.getOrDefault(def.id(), false),
                            v -> {
                                config.featureToggles.put(def.id(), v);
                                try {
                                    FarmHelperFabric.getFeatureManager().setFeatureEnabled(def.id(), v);
                                } catch (Exception ignored) {}
                            }
                    )
                    .controller(TickBoxControllerBuilder::create)
                    .build());
        }

        return builder.build();
    }
