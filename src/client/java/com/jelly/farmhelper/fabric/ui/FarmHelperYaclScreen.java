    private static String enumOptionsText(Class<? extends Enum<?>> enumClass) {
        Enum<?>[] values = enumClass == null ? null : enumClass.getEnumConstants();
        if (values == null || values.length == 0) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        for (Enum<?> value : values) {
            if (!sb.isEmpty()) {
                sb.append(", ");
            }
            sb.append(value.name());
        }
        return sb.toString();
    }
